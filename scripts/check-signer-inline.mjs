// Build-time guard against the signer WASM drift that shipped in 1.0.24/1.0.25:
// the app instantiates the signer from the inlined base64 (src/signer/wasm-base64.ts),
// NOT the .wasm file, and NOT from the JS glue in isolation. If the inlined bytes
// drift from the committed .wasm, or the wasm imports a wbg function the glue no
// longer provides, wallet creation dies with
//   "WebAssembly.instantiate(): Import #2 \"wbg\" \"__wbindgen_is_object\": function import requires a callable"
// This runs on EVERY `npm run build`, so a drifted tree fails the build instead of
// shipping. (test/signer-inline.test.ts covers the same thing under vitest.)
import { readFileSync } from "node:fs";
import { createHash } from "node:crypto";

const dir = new URL("../src/signer/", import.meta.url);
const b64 = readFileSync(new URL("wasm-base64.ts", dir), "utf8").match(/WASM_B64 = "([^"]+)"/)?.[1];
if (!b64) fail("could not read WASM_B64 from src/signer/wasm-base64.ts");
const inlined = Buffer.from(b64, "base64");
const file = readFileSync(new URL("firecash_signer_bg.wasm", dir));
const glue = readFileSync(new URL("firecash_signer.js", dir), "utf8");

const sha = (b) => createHash("sha256").update(b).digest("hex");
if (sha(inlined) !== sha(file)) {
  fail(`inlined WASM (${sha(inlined).slice(0, 12)}) != committed firecash_signer_bg.wasm (${sha(file).slice(0, 12)}).\n` +
       `Regenerate: node -e 'import("node:fs").then(fs=>{const w=fs.readFileSync("src/signer/firecash_signer_bg.wasm");fs.writeFileSync("src/signer/wasm-base64.ts",\`// AUTO-GENERATED by build-wallet-stack.sh — do not edit.\\nexport const WASM_B64 = "\${w.toString("base64")}";\\n\`)})'`);
}

const mod = new WebAssembly.Module(inlined);
const missing = WebAssembly.Module.imports(mod)
  .filter((i) => i.module === "wbg" && !glue.includes(`imports.wbg.${i.name}`))
  .map((i) => i.name);
if (missing.length) fail(`the inlined WASM imports wbg functions the JS glue does not provide: ${missing.join(", ")}. The .wasm and firecash_signer.js are from different wasm-bindgen builds.`);

console.log(`signer inline OK — wasm ${sha(file).slice(0, 12)}, all wbg imports satisfied`);

function fail(msg) {
  console.error(`\n✗ signer WASM drift: ${msg}\n`);
  process.exit(1);
}
