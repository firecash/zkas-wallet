#!/usr/bin/env node
// Generate ios/App/App/<lang>.lproj/InfoPlist.strings from the i18n catalogues.
//
// iOS reads permission prompts from InfoPlist.strings, NOT from the app's own catalogue,
// so without these the camera and Face ID prompts are English on every device — while the
// rest of the wallet is translated into 24 languages. Android gets its permission dialogs
// localised by the system and needs none of this.
//
// Generated rather than hand-written so the strings stay in step with the catalogue the
// translators actually fill: the source of truth is iosPermission.* in
// src/i18n/locales/<lang>.json.
import { readFileSync, writeFileSync, mkdirSync, readdirSync } from "node:fs";

const LOCALES = "src/i18n/locales";
// English lives in partials (src/i18n/en/*.json), merged at build time; the translated
// languages are one flat file each.
const EN_PARTIALS = "src/i18n/en";
const OUT = "ios/App/App";
// Apple's directory names do not always match the i18n tags.
const LPROJ = { "pt-BR": "pt-BR", "zh-CN": "zh-Hans", "zh-TW": "zh-Hant" };

// The Info.plist keys, and which catalogue string fills each.
const KEYS = {
  NSCameraUsageDescription: "camera",
  NSFaceIDUsageDescription: "faceId",
};

/** .strings is its own format: C-style escapes, double quotes, semicolon-terminated. */
const esc = (s) => s.replace(/\\/g, "\\\\").replace(/"/g, '\\"').replace(/\n/g, "\\n");

/** English, merged from the partials the app itself merges. */
function english() {
  const out = {};
  for (const f of readdirSync(EN_PARTIALS).filter((f) => f.endsWith(".json"))) {
    Object.assign(out, JSON.parse(readFileSync(`${EN_PARTIALS}/${f}`, "utf8")));
  }
  return out;
}

let written = 0;
const langs = [["en", english()]];
for (const f of readdirSync(LOCALES).filter((f) => f.endsWith(".json") && !f.startsWith("."))) {
  langs.push([f.replace(/\.json$/, ""), JSON.parse(readFileSync(`${LOCALES}/${f}`, "utf8"))]);
}
for (const [lang, cat] of langs) {
  const file = `${lang}.json`;
  const perm = cat.iosPermission;
  if (!perm) {
    console.warn(`  ${lang}: no iosPermission block — skipped (run scripts/translate.mjs)`);
    continue;
  }
  const lines = [];
  for (const [plistKey, catKey] of Object.entries(KEYS)) {
    const value = perm[catKey];
    if (!value) continue;
    lines.push(`"${plistKey}" = "${esc(value)}";`);
  }
  if (lines.length !== Object.keys(KEYS).length) {
    console.warn(`  ${lang}: only ${lines.length}/${Object.keys(KEYS).length} strings — skipped`);
    continue;
  }
  const dir = `${OUT}/${LPROJ[lang] ?? lang}.lproj`;
  mkdirSync(dir, { recursive: true });
  // UTF-8 with a header naming the generator, so nobody edits the output by hand.
  writeFileSync(`${dir}/InfoPlist.strings`,
    `/* Generated by scripts/ios-infoplist-strings.mjs from src/i18n/locales/${file} — do not edit. */\n${lines.join("\n")}\n`, "utf8");
  written += 1;
}
console.log(`InfoPlist.strings written for ${written} language(s)`);
